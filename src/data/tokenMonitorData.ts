// Generate smooth realistic sparkline relative coordinates
function generateSparkline(basePrice: number, change7d: number, volatility: number = 0.03): number[] {
  const points: number[] = [];
  let current = basePrice / (1 + change7d / 100);
  const steps = 24; // 24 points across 7 days
  const trendStep = (basePrice - current) / steps;

  for (let i = 0; i < steps; i++) {
    const randomNoise = (Math.sin(i * 0.8) * 0.5 + Math.cos(i * 1.3) * 0.5) * volatility * basePrice;
    current += trendStep + randomNoise;
    points.push(Number(Math.max(current, basePrice * 0.5).toFixed(4)));
  }
  points.push(basePrice);
  return points;
}

